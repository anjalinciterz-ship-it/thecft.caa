/* One-time font fetch, kept so the self-hosted faces can be refreshed later.
 * Run with `node scripts/fetch-fonts.mjs`. It needs the network, and it is never
 * part of `npm run build`: the WOFF2 files it writes into public/fonts are the
 * files the site ships, so typography does not depend on Google being reachable.
 *
 * All three families are variable fonts, so each one is a single file that covers
 * a weight range instead of one file per weight. The script asks Google's css2
 * API for the ranges the site uses, with a modern browser's user-agent so the
 * response is WOFF2, keeps only the `latin` subset (that range covers the
 * punctuation the copy actually uses, curly quotes and en dashes included),
 * downloads each face and rewrites the @font-face rules to point at the local
 * files.
 */
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36';

// The weights below are the ones the stylesheets actually ask for: see
// --font-head, --font-body and --font-script in global.css.
const WANTED = [
  { query: 'Manrope:wght@400..800', slug: 'manrope', family: 'Manrope', style: 'normal', weight: '400 800' },
  { query: 'Cormorant+Garamond:wght@600..700', slug: 'cormorant-garamond', family: 'Cormorant Garamond', style: 'normal', weight: '600 700' },
  { query: 'Cormorant+Garamond:ital,wght@1,600', slug: 'cormorant-garamond', family: 'Cormorant Garamond', style: 'italic', weight: '600' },
  { query: 'Caveat:wght@600..700', slug: 'caveat', family: 'Caveat', style: 'normal', weight: '600 700' },
];

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const fontDir = path.join(root, 'public', 'fonts');

async function latinFace(query) {
  const css = await (
    await fetch(`https://fonts.googleapis.com/css2?family=${query}&display=swap`, { headers: { 'user-agent': UA } })
  ).text();
  // Google marks each subset with a comment before the block that serves it.
  const block = css.split(/(?=\/\*\s)/).find((b) => /^\/\*\s*latin\s*\*\//.test(b.trim()) && b.includes('@font-face'));
  if (!block) throw new Error(`no latin face for ${query}; Google changed the response format`);
  return { url: /src:\s*url\(([^)]+)\)/.exec(block)[1], range: /unicode-range:\s*([^;]+);/.exec(block)[1].trim() };
}

await mkdir(fontDir, { recursive: true });
const rules = [];
for (const w of WANTED) {
  const { url, range } = await latinFace(w.query);
  const name = `${w.slug}-${w.style === 'italic' ? 'italic' : 'normal'}-latin.woff2`;
  const bytes = Buffer.from(await (await fetch(url, { headers: { 'user-agent': UA } })).arrayBuffer());
  await writeFile(path.join(fontDir, name), bytes);
  rules.push(
    `@font-face{font-family:'${w.family}';font-style:${w.style};font-weight:${w.weight};` +
      `font-display:swap;src:url('/fonts/${name}') format('woff2');unicode-range:${range};}`,
  );
  console.log(name.padEnd(40), (bytes.byteLength / 1024).toFixed(1) + ' KB');
}
await writeFile(
  path.join(root, 'src', 'styles', 'fonts.css'),
  `/* Generated by scripts/fetch-fonts.mjs. Self-hosted variable WOFF2, latin subset,\n` +
    `   font-display:swap. These are the only faces the site uses: Manrope for body\n` +
    `   copy, Cormorant Garamond for headings, Caveat for the one handwritten accent.\n` +
    `   Keep the ranges in sync with --font-* in global.css. */\n` +
    rules.join('\n') + '\n',
);
console.log(`\n${rules.length} faces -> public/fonts, rules -> src/styles/fonts.css`);
